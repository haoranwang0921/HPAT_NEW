# =============================================================================
# hpat_eval 包说明
# =============================================================================
# 本文件只是 Python 包的 __init__.py，本身不包含任何可执行逻辑，
# 作用是声明 hpat_eval 目录是一个 Python 包，使其他脚本可以通过
#   from hpat_eval import xxx
# 的形式导入本目录下的各个功能模块（能耗建模、活动轨迹、证据评估等）。
#
# HPAT 背景：HPAT（光子张量处理器）是一种用于光矩阵乘法的光子计算架构，
# 包含 12 Tile × 8 Core = 96 个 Core，每个 Core 内有 64×64 个 MRR
# （微环谐振器，光信号的开光/调制器件），共约 39 万个 MRR。
# 本库 hpat_eval 即是为该架构做能耗、误差、可复现性等评估的可复用代码。
# =============================================================================

